/**
 * LAB NOTES — formatador determinístico de especificações + cálculo.
 * Zero IA: só concatena o que o algoritmo BigInt já computou.
 */
import { P, N, A, B, GX, GY } from "./secp256k1.js";
import { bigToHex } from "./modular.js";
import { isInf, compress, fmtPt } from "./point.js";

function H(n, w = 64) {
  if (n == null) return "—";
  if (typeof n === "bigint") return bigToHex(n, w);
  return String(n);
}

function ptBlock(label, Pt) {
  if (isInf(Pt) || Pt?.inf) {
    return [
      `${label} = O (point at infinity)`,
      `  compressed: ∞`,
    ];
  }
  // accept either raw {x,y} BigInt or fmtPt object
  if (typeof Pt.x === "string") {
    return [
      `${label}:`,
      `  compressed: ${Pt.compressed}`,
      `  x = ${Pt.x}`,
      `  y = ${Pt.y}`,
    ];
  }
  return [
    `${label}:`,
    `  compressed: ${compress(Pt)}`,
    `  x = ${H(Pt.x)}`,
    `  y = ${H(Pt.y)}`,
  ];
}

export function curveSpecLines() {
  return [
    "══ CURVE SPEC ══",
    "name: secp256k1  (SEC2 / Bitcoin)",
    "eq:   y² = x³ + a·x + b   (mod p)",
    `a = ${H(A, 1)}`,
    `b = ${H(B, 1)}`,
    `p = ${H(P)}`,
    `n = ${H(N)}   (order of subgroup generated by G)`,
    `Gx = ${H(GX)}`,
    `Gy = ${H(GY)}`,
    "G_compressed = 0279be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798",
    "engine: deterministic BigInt (js/core/*) — no AI, no network, no heuristics",
  ];
}

export function algoForwardSpec() {
  return [
    "══ ALGORITHM forward (MSB-first Double-and-Add) ══",
    "NOT «all ×2 then all +G».",
    "It is PER BIT, interleaved (MSB → LSB):",
    "input: k ∈ [1, n−1]   R ← O",
    "for i = L−1 downto 0:",
    "  R ← 2·R                 // Double ALWAYS on this bit",
    "  if bit_i(k) = 1:",
    "    R ← R + G             // Add only if bit=1",
    "output: Q = k·G = R",
    "e.g. k=13=1101₂ → D,A, D,A, D, D,A  (not D,D,D,D + A,A,A).",
  ];
}

export function algoReverseSpec() {
  return [
    "══ ALGORITHM reverse (undo MSB-first, i = 0..L−1) ══",
    "input: Q = k·G, maxBit = L−1, known/candidate bits",
    "R ← Q",
    "for i = 0 .. maxBit:",
    "  if bit_i = 0:  R ← half(R)         // undo Double without Add",
    "  if bit_i = 1:  R ← half(R − G)     // undo Add then Double",
    "half(P) := (2⁻¹ mod n) · P          // UNIQUE in the order-n subgroup",
    "ambiguity: only if there was an Add (bit), NOT in half",
    "close: complete bits ∧ R = O  ⇒  k reconstructed",
    "NOT an ECDLP solver — needs indices (or a search over candidates).",
  ];
}

/**
 * Full notes for an add/double/copy/inf trace from addDetailed.
 */
export function formatAddTraceNotes(trace, ctx = {}) {
  const lines = [];
  lines.push("══ EC OPERATION (algorithm) ══");
  lines.push(`op_branch = ${trace.op}`);
  lines.push(`why: ${trace.why || "—"}`);
  if (ctx.kind) lines.push(`role_in_D&A: ${ctx.kind}`);
  if (ctx.bitIndex != null) {
    lines.push(`bitIndex = ${ctx.bitIndex}   bit = ${ctx.bit}`);
    lines.push(`D_so_far = ${ctx.doublesSoFar ?? "—"}   A_so_far = ${ctx.addsSoFar ?? "—"}`);
  }
  if (ctx.algoWhy) lines.push(`rule: ${ctx.algoWhy}`);
  lines.push("");
  lines.push("── Formula ──");
  lines.push(trace.formula || "—");
  lines.push("");

  if (trace.P1 !== undefined) {
    lines.push(...ptBlock("P1 (input)", trace.P1));
    lines.push(...ptBlock("P2 (input)", trace.P2));
    lines.push("");
  }

  if (trace.op === "double" || trace.op === "add") {
    lines.push("── Intermediates (mod p) ──");
    if (trace.op === "double") {
      lines.push("λ = (3·x₁² + a) · (2·y₁)⁻¹   with a=0 ⇒ numer=3·x₁²");
    } else {
      lines.push("λ = (y₂ − y₁) · (x₂ − x₁)⁻¹");
    }
    lines.push(`numer     = ${H(trace.numer)}`);
    lines.push(`denom     = ${H(trace.denom)}`);
    lines.push(`denom⁻¹   = ${H(trace.invDenom)}`);
    lines.push(`λ         = ${H(trace.lambda)}`);
    if (trace.lambdaSq != null) lines.push(`λ²        = ${H(trace.lambdaSq)}`);
    lines.push(`x₃        = ${H(trace.x3)}`);
    lines.push(`y₃        = ${H(trace.y3)}`);
    lines.push("");
    lines.push("── Steps ──");
    for (const s of trace.steps || []) lines.push("  " + s);
  } else if (trace.op === "copy") {
    lines.push("── Identity branch ──");
    lines.push("one operand is O ⇒ result = the other point (no λ).");
    for (const s of trace.steps || []) lines.push("  " + s);
  } else if (trace.op === "inf") {
    lines.push("── Infinity branch ──");
    lines.push("P + (−P) = O");
    for (const s of trace.steps || []) lines.push("  " + s);
  }

  lines.push("");
  if (trace.resultPt) {
    lines.push(...ptBlock("result", trace.resultPt));
  } else if (trace.x3 != null) {
    lines.push(`result x₃=${H(trace.x3)}`);
    lines.push(`result y₃=${H(trace.y3)}`);
  } else if (trace.op === "inf") {
    lines.push("result = O (∞)");
  }

  if (trace.onCurveOk != null) {
    lines.push(`onCurve(result) = ${trace.onCurveOk}`);
  }
  return lines.join("\n");
}

/**
 * Full notes for halfDetailed.
 */
export function formatHalfTraceNotes(trace, ctx = {}) {
  const lines = [];
  lines.push("══ HALF (algorithm) ══");
  lines.push("definition: H = (2⁻¹ mod n) · P");
  lines.push("existence/uniqueness: n odd ⇒ 2 invertible mod n;");
  lines.push("  in subgroup ⟨G⟩ of order n, half is a bijection (inverse of Double).");
  if (ctx.bit != null) {
    lines.push(`use in reverse: bit=${ctx.bit}  →  ${ctx.bit === 1 ? "half(R−G)" : "half(R)"}`);
  }
  if (ctx.bitIndex != null) lines.push(`bitIndex = ${ctx.bitIndex}`);
  lines.push("");
  lines.push("── Formula ──");
  lines.push(trace.formula || "H = inv2 · P");
  lines.push("");
  if (trace.input) lines.push(...ptBlock("P (input)", trace.input));
  lines.push(`2⁻¹ mod n = ${H(trace.inv2)}`);
  lines.push(`n         = ${H(N)}`);
  lines.push("");
  lines.push("── Steps ──");
  for (const s of trace.steps || []) lines.push("  " + s);
  lines.push("");
  if (trace.result) lines.push(...ptBlock("H = half(P)", trace.result));
  if (trace.verify2H) {
    lines.push("");
    lines.push("── Algorithmic check: 2·H ≟ P ──");
    lines.push(...ptBlock("2·H", trace.verify2H));
    lines.push(`2·H == P ? ${trace.verifyOk ? "YES ✓" : "NO ✗"}`);
  }
  lines.push("");
  lines.push("engine: BigInt scalar mul of inv2 · P — deterministic, no AI");
  return lines.join("\n");
}

/** Combined reverse bit=1: sub then half. */
export function formatHalf1Notes(subTrace, halfTrace, ctx = {}) {
  const lines = [];
  lines.push("══ REVERSE bit=1 · half(R − G) ══");
  lines.push("step 1: S = R − G = R + (−G)");
  lines.push("step 2: H = half(S) = (2⁻¹ mod n) · S");
  lines.push(`bitIndex = ${ctx.bitIndex ?? "—"}`);
  lines.push("");
  lines.push("──── (1) SUBTRACTION R−G ────");
  lines.push(formatAddTraceNotes(subTrace, { kind: "sub G", algoWhy: "undoes the forward Add" }));
  lines.push("");
  lines.push("──── (2) HALF ────");
  lines.push(formatHalfTraceNotes(halfTrace, { bit: 1, bitIndex: ctx.bitIndex }));
  return lines.join("\n");
}

/** Seed / algorithm banner notes. */
export function formatSeedForwardNotes(priv) {
  return [
    ...algoForwardSpec(),
    "",
    "── Scalar k ──",
    `k_hex = ${priv.hex}`,
    `k_dec = ${priv.dec}`,
    `bitlen L = ${priv.bitLength}`,
    `bin (MSB..LSB) = ${priv.bin}`,
    `hamming wt = ${priv.hamming}`,
    `ADD indices (LSB) = [${priv.setBitsLSB.join(", ")}]`,
    "",
    ...curveSpecLines(),
  ].join("\n");
}

export function formatSeedReverseNotes(maxBit, Qfmt) {
  return [
    ...algoReverseSpec(),
    "",
    `maxBit = ${maxBit}  ⇒  L = ${maxBit + 1}`,
    ...ptBlock("Q (pubkey)", Qfmt),
    "",
    ...curveSpecLines(),
  ].join("\n");
}

/** Forward op row notes from serialized engine op. */
function hexToBigOrNull(h) {
  if (!h) return null;
  return BigInt("0x" + String(h).replace(/^0x/i, ""));
}

export function formatForwardOpNotes(op) {
  let branch = op.math?.opBranch;
  if (!branch) {
    if (op.math?.formula === "O + P = P" || op.math?.formula === "P + O = P") {
      branch = "copy";
    } else if (op.math?.formula === "P + (−P) = O") {
      branch = "inf";
    } else if (op.kind === "double") {
      branch = "double";
    } else {
      branch = "add";
    }
  }
  const trace = {
    op: branch,
    formula: op.math.formula,
    why: op.math.whyMath || op.why,
    lambda: hexToBigOrNull(op.math.lambda),
    numer: hexToBigOrNull(op.math.numer),
    denom: hexToBigOrNull(op.math.denom),
    invDenom: hexToBigOrNull(op.math.invDenom),
    lambdaSq: hexToBigOrNull(op.math.lambdaSq),
    x3: op.R_after?.inf ? null : hexToBigOrNull(op.R_after?.x),
    y3: op.R_after?.inf ? null : hexToBigOrNull(op.R_after?.y),
    steps: op.math.steps || [],
    P1: op.R_before,
    P2: op.kind === "add" ? op.addend : op.R_before,
    resultPt: op.R_after,
    onCurveOk: op.math.onCurveOk,
  };

  return formatAddTraceNotes(trace, {
    kind: op.kind,
    bitIndex: op.bitIndex,
    bit: op.bit,
    doublesSoFar: op.doublesSoFar,
    addsSoFar: op.addsSoFar,
    algoWhy: op.why,
  });
}

